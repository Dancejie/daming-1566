function parseJsonObject(content) {
  try {
    return JSON.parse(content || "{}");
  } catch (error) {
    const match = String(content || "").match(/\{[\s\S]*\}/);
    if (!match) throw error;
    return JSON.parse(match[0]);
  }
}

async function askModel(playerText, intent, options = {}) {
  const provider = providerSelect.value;
  const apiKey = apiKeyInput.value.trim();
  const endpoint = endpointInput.value.trim();
  const scene = currentScene();
  const focusId = options.replyBy || "director";
  const focusName = focusId === "director" ? "Director" : state.agents[focusId]?.name;
  if (state.isGenerating) {
    setReasoningFocus(
      focusId,
      `${focusName} 正在读取玩家输入、前序发言、世界变量和人物记忆，生成本轮可公开回应。`
    );
  }

  if (provider === "mock") {
    return options.replyBy
      ? buildCharacterOutcome(options.replyBy, playerText, intent, scene, options.transcript)
      : buildFallbackOutcome(playerText, intent, scene);
  }
  if ((provider === "openai" || provider === "deepseek-direct") && (!apiKey || !endpoint)) {
    return options.replyBy
      ? buildCharacterOutcome(options.replyBy, playerText, intent, scene, options.transcript)
      : buildFallbackOutcome(playerText, intent, scene);
  }

  modelState.textContent = "请求中";
  try {
    const prompt = buildPromptForModel(playerText, intent, options);
    const response = provider === "deepseek"
      ? await fetch(endpoint || "/api/deepseek", {
          method: "POST",
          headers: { "Content-Type": "application/json" },
          body: JSON.stringify({ prompt, intent, sceneId: scene.id, replyBy: options.replyBy || null })
        })
      : await fetch(endpoint, {
          method: "POST",
          headers: {
            "Content-Type": "application/json",
            Authorization: `Bearer ${apiKey}`
          },
          body: JSON.stringify({
            model: provider === "deepseek-direct" ? "deepseek-chat" : "gpt-4.1-mini",
            messages: [
              { role: "system", content: "你只输出可解析 JSON。你是历史权谋互动叙事 Director Agent。" },
              { role: "user", content: prompt }
            ],
            temperature: 0.8,
            response_format: { type: "json_object" }
          })
        });

    if (!response.ok) {
      throw new Error(`API ${response.status}`);
    }

    const data = await response.json();
    const parsed = provider === "deepseek"
      ? data.result
      : parseJsonObject(data.choices?.[0]?.message?.content);
    return normalizeModelOutcome(parsed, playerText, intent, scene, options);
  } catch (error) {
    modelState.textContent = provider === "deepseek" ? "DeepSeek 未连接，已本地兜底" : "本地兜底";
    return options.replyBy
      ? buildCharacterOutcome(options.replyBy, playerText, intent, scene, options.transcript)
      : buildFallbackOutcome(playerText, intent, scene);
  }
}


function configureProvider() {
  const provider = providerSelect.value;
  modelState.textContent = provider === "mock" ? "本地演示" : provider === "deepseek" ? "DeepSeek 代理待连接" : provider === "deepseek-direct" ? "DeepSeek 直连待配置" : "待配置";
  if (provider === "deepseek") {
    if (!endpointInput.value || endpointInput.value.startsWith("https://api.")) endpointInput.value = "/api/deepseek";
    apiKeyInput.disabled = true;
  } else if (provider === "deepseek-direct") {
    if (!endpointInput.value || endpointInput.value === "/api/deepseek") endpointInput.value = "https://api.deepseek.com/chat/completions";
    apiKeyInput.disabled = false;
  } else {
    apiKeyInput.disabled = false;
  }
  if (provider === "openai" && (!endpointInput.value || endpointInput.value === "/api/deepseek")) {
    endpointInput.value = "https://api.openai.com/v1/chat/completions";
  }
}

function configureVoiceProvider() {
  const provider = voiceProviderSelect?.value || "proxy";
  if (!voiceEndpointInput) return;
  if (provider === "proxy" && (!voiceEndpointInput.value || voiceEndpointInput.value.endsWith(":9880"))) {
    voiceEndpointInput.value = "/api/tts";
  }
  if (provider === "gpt-sovits" && (!voiceEndpointInput.value || voiceEndpointInput.value === "/api/tts")) {
    voiceEndpointInput.value = "http://127.0.0.1:9880";
  }
  voiceState.directSpeaker = null;
}

function loadConnectionConfig() {
  try {
    const config = JSON.parse(localStorage.getItem(configStorageKey) || "{}");
    if (config.provider) providerSelect.value = config.provider;
    if (config.endpoint) endpointInput.value = config.endpoint;
    if (config.apiKey) apiKeyInput.value = config.apiKey;
    if (voiceProviderSelect && config.voiceProvider) voiceProviderSelect.value = config.voiceProvider;
    if (voiceEndpointInput && config.voiceEndpoint) voiceEndpointInput.value = config.voiceEndpoint;
  } catch (error) {
    localStorage.removeItem(configStorageKey);
  }
}

function saveConnectionConfig() {
  const config = {
    provider: providerSelect.value,
    endpoint: endpointInput.value.trim(),
    apiKey: apiKeyInput.value.trim(),
    voiceProvider: voiceProviderSelect?.value || "proxy",
    voiceEndpoint: voiceEndpointInput?.value.trim() || "/api/tts"
  };
  localStorage.setItem(configStorageKey, JSON.stringify(config));
}

async function checkDeepSeekHealth() {
  if (providerSelect.value === "mock") {
    modelBadge.textContent = "本地演示";
    return;
  }
  if (providerSelect.value === "deepseek-direct" || providerSelect.value === "openai") {
    modelBadge.textContent = apiKeyInput.value.trim() ? "直连已配置" : "直连缺少 Key";
    modelState.textContent = apiKeyInput.value.trim() ? "直连待请求" : "直连缺少 Key";
    return;
  }
  try {
    const response = await fetch("/api/health");
    const data = await response.json();
    if (data.deepseekConfigured) {
      modelBadge.textContent = `DeepSeek 已连接`;
      if (providerSelect.value === "deepseek") modelState.textContent = `DeepSeek 已连接 · ${data.model}`;
    } else {
      modelBadge.textContent = "DeepSeek 未配置";
      if (providerSelect.value === "deepseek") modelState.textContent = "DeepSeek 未配置 key";
    }
  } catch (error) {
    modelBadge.textContent = "DeepSeek 未连接";
    if (providerSelect.value === "deepseek") modelState.textContent = "DeepSeek 未连接";
  }
}


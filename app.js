function mergeDeltas(base = {}, extra = {}) {
  const merged = structuredClone(base);
  Object.entries(extra).forEach(([key, value]) => {
    merged[key] = (merged[key] || 0) + value;
  });
  return merged;
}

function mergeAgentDeltas(base = {}, extra = {}) {
  const merged = structuredClone(base);
  Object.entries(extra).forEach(([agentId, deltas]) => {
    merged[agentId] = mergeDeltas(merged[agentId] || {}, deltas);
  });
  return merged;
}


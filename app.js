function clamp(value) {
  return Math.max(0, Math.min(100, Math.round(value)));
}

function applyDelta(target, deltas = {}) {
  Object.entries(deltas).forEach(([key, value]) => {
    target[key] = clamp((target[key] ?? 0) + value);
  });
}

function classifyInput(text) {
  const lower = text.toLowerCase();
  if (/制度|章程|清丈|考成|税|法|新政|结构|分账|方案|数据|原账/.test(text)) return "system";
  if (/三日|暂缓|等|忍|时机|藏|副本|收网/.test(text)) return "timing";
  if (/军|饷|海防|前线|粮道|倭|士卒|断粮/.test(text)) return "frontline";
  if (/银|钱|粮|赈|国库|活路|开仓|交易|相府/.test(text)) return "money";
  if (/百姓|民|活人|灾民|无辜|人命|粥/.test(text)) return "people";
  if (/清官|清白|真相|公堂|上疏|证据|账册|公开|作证/.test(text)) return "justice";
  if (lower.includes("皇") || /圣意|皇权|陛下|内廷|密旨|西苑/.test(text)) return "imperial";
  return "balanced";
}

function uniqueChain(items) {
  return items.filter((item, index) => item && items.indexOf(item) === index);
}

function buildReasoningChain(playerText, intent, preferredFirst = null) {
  const scene = currentScene();
  const opening = preferredFirst ? [] : ["director"];
  const order = uniqueChain([...opening, preferredFirst, ...scene.participants]);
  const intentNames = {
    system: "制度案",
    timing: "时机",
    frontline: "军饷海防",
    money: "银路",
    people: "民生",
    justice: "真相",
    imperial: "皇权",
    balanced: "折中"
  };

  return order.map((id, index) => {
    const agent = state.agents[id];
    const name = id === "director" ? "Director" : agent.name;
    const role = id === "director" ? "剧情调度" : agent.role;
    const text = playerText.length > 22 ? `${playerText.slice(0, 22)}...` : playerText;
    return {
      id,
      name,
      role,
      status: index === 0 ? "current" : "waiting",
      detail: `${publicReasoningHints[id]} 当前输入被标记为「${intentNames[intent] || intent}」：${text}`
    };
  });
}

function beginReasoning(playerText, intent, preferredFirst = null) {
  state.thinkingSteps = buildReasoningChain(playerText, intent, preferredFirst);
  state.thinkingFocus = state.thinkingSteps[0]?.name || "DeepSeek";
  state.keepThoughts = true;
  renderThoughtRail();
}

function setReasoningFocus(agentId, detail = "") {
  let touched = false;
  state.thinkingSteps = state.thinkingSteps.map((step) => {
    if (step.id === agentId) {
      touched = true;
      return { ...step, status: "current", detail: detail || step.detail };
    }
    if (step.status === "current") return { ...step, status: "done" };
    return step;
  });

  if (!touched && agentId) {
    const agent = state.agents[agentId];
    state.thinkingSteps.push({
      id: agentId,
      name: agent?.name || "Agent",
      role: agent?.role || "串行回应",
      status: "current",
      detail: detail || publicReasoningHints[agentId] || "综合上文生成下一句回应。"
    });
  }

  const active = state.thinkingSteps.find((step) => step.status === "current");
  state.thinkingFocus = active ? `${active.name} 正在生成` : "整理回合结果";
  renderThoughtRail();
}

function setReasoningResult(agentId, psychology = "") {
  if (!agentId) return;
  const agent = state.agents[agentId];
  const fallback = agent
    ? `${agent.name} 把这句话先压在心里，衡量它会不会伤到自己的底线，也衡量它能否成为下一步的筹码。`
    : "这一轮回应把玩家输入、上下文与世界变量重新压进局面里，等待下一句爆开。";
  state.thinkingSteps = state.thinkingSteps.map((step) => {
    if (step.id !== agentId) return step;
    return {
      ...step,
      status: "done",
      detail: psychology || fallback
    };
  });
  state.thinkingFocus = state.isGenerating ? "串行生成中" : "本轮暗线";
  renderThoughtRail();
}

function completeReasoning() {
  state.thinkingSteps = state.thinkingSteps.map((step) => ({ ...step, status: "done" }));
  state.thinkingFocus = "本轮暗线";
  renderThoughtRail();
}

function clearReasoning() {
  state.thinkingSteps = [];
  state.thinkingFocus = "等待玩家进言";
  state.keepThoughts = false;
  renderThoughtRail();
}


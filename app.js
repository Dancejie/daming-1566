function enterScene(index) {
  state.sceneIndex = Math.max(0, Math.min(index, scenes.length - 1));
  const scene = currentScene();
  state.activeAgent = playerAgentForScene(scene) || scene.participants[0] || "jiajing";
  selectedAgent = state.activeAgent;
  const coverLines = scene.mode === "classic"
    ? [makeLine("章回", buildSceneCoverText(scene), { type: "cover" })]
    : [];
  enqueueLines([...coverLines, ...scene.intro.map((line) => makeLine(line.speaker, line.text, {
    type: line.type || "",
    voiceText: line.voiceText || "",
    voiceClipId: line.voiceClipId || ""
  }))]);
}

function advanceTo(sceneId) {
  if (!sceneId) return;
  const index = scenes.findIndex((scene) => scene.id === sceneId);
  if (index >= 0 && index !== state.sceneIndex) enterScene(index);
}


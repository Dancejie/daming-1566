function normalizeModelOutcome(parsed, playerText, intent, scene, options = {}) {
  parsed = parsed || {};
  const terminal = !options.replyBy ? detectTerminalEnding(playerText, intent) : null;
  const fallback = buildFallbackOutcome(playerText, intent, scene);
  const characterFallback = options.replyBy ? buildCharacterOutcome(options.replyBy, playerText, intent, scene, options.transcript) : fallback;
  const replyBy = terminal ? fallback.replyBy : (options.replyBy || (agentProfiles[parsed.replyBy] ? parsed.replyBy : fallback.replyBy));
  const impact = !options.replyBy ? evaluatePlayerImpact(playerText, intent) : { world: {}, agents: {} };
  const fork = !options.replyBy ? detectFork(playerText, intent) : null;
  const allowedNext = ["S001", "S002", "S003", "S004", "S005", "S006", "X001", "X002", "X003", null];
  const parsedNext = allowedNext.includes(parsed.next) ? parsed.next : fallback.next;
  const isTerminal = Boolean(!options.replyBy && (terminal || parsed.terminal === true || parsed.next === "END"));
  return {
    replyBy,
    speaker: state.agents[replyBy].name,
    mood: terminal ? fallback.mood : (typeof parsed.mood === "string" && parsed.mood.trim() ? parsed.mood.trim() : state.agents[replyBy].mood),
    reply: terminal ? fallback.reply : (parsed.reply || characterFallback.reply),
    voiceText: terminal ? (fallback.voiceText || "") : (typeof parsed.voiceText === "string" && parsed.voiceText.trim() ? parsed.voiceText.trim() : characterFallback.voiceText || ""),
    psychology: terminal ? fallback.psychology : (typeof parsed.psychology === "string" && parsed.psychology.trim() ? parsed.psychology.trim() : characterFallback.psychology),
    system: options.replyBy ? "" : (isTerminal ? (terminal ? fallback.system : (parsed.system || fallback.system)) : (fork ? `脱轨触发：${fork.reason} 主线将跳转至隐藏分支。` : (parsed.system || fallback.system))),
    world: options.replyBy ? {} : mergeDeltas(mergeDeltas(parsed.world && typeof parsed.world === "object" ? parsed.world : fallback.world, impact.world), fork?.world || {}),
    agents: mergeAgentDeltas(mergeAgentDeltas(parsed.agents && typeof parsed.agents === "object" ? parsed.agents : characterFallback.agents, impact.agents), fork?.agents || {}),
    memories: parsed.memories && typeof parsed.memories === "object" ? parsed.memories : characterFallback.memories,
    next: options.replyBy || isTerminal ? null : (fork?.next || (parsedNext === null ? null : parsedNext || fallback.next)),
    terminal: isTerminal,
    endingTitle: typeof parsed.endingTitle === "string" && parsed.endingTitle.trim() ? parsed.endingTitle.trim() : fallback.endingTitle
  };
}


function trimTtsText(text, maxChars = 100) {
  const normalized = String(text || "").replace(/\s+/g, " ").trim().replace(/^[：:，。；;]+|[：:，。；;]+$/g, "");
  if (normalized.length <= maxChars) return normalized;
  const cut = normalized.slice(0, maxChars);
  const sentenceEnd = Math.max(cut.lastIndexOf("。"), cut.lastIndexOf("？"), cut.lastIndexOf("！"));
  return sentenceEnd >= 40 ? cut.slice(0, sentenceEnd + 1) : cut;
}

function extractSpokenDialogue(line) {
  if (!line || line.type === "system" || line.type === "player") return "";
  if (line.voiceClipId) return trimTtsText(line.voiceText || line.text);
  if (!line.agentId || !voiceEnabledAgents.has(line.agentId)) return "";
  if (line.voiceText) return trimTtsText(line.voiceText);
  let text = String(line.text || "").replace(/\s+/g, " ").trim();
  const quoted = [...text.matchAll(/[“「『](.+?)[”」』]/g)].map((match) => match[1].trim()).filter(Boolean);
  if (quoted.length) {
    const useful = quoted.filter((part) => part.length > 2);
    const selected = useful.length ? useful.slice(0, 2) : quoted.slice(0, 1);
    return trimTtsText(selected.join("。"));
  }

  if (text.includes("：")) text = text.split("：").pop().trim();
  const anchors = line.agentId === "jiajing" ? ["朕"] : ["老夫", "姑娘", "你"];
  for (const anchor of anchors) {
    const index = text.indexOf(anchor);
    if (index >= 0) {
      text = text.slice(index);
      break;
    }
  }
  return trimTtsText(text);
}


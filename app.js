function applyOutcome(outcome) {
  applyDelta(state.world, outcome.world);
  Object.entries(outcome.agents || {}).forEach(([agentId, deltas]) => {
    if (state.agents[agentId]) applyDelta(state.agents[agentId].traits, deltas);
  });
  Object.entries(outcome.memories || {}).forEach(([agentId, memory]) => {
    if (state.agents[agentId]) state.agents[agentId].memory = memory;
  });
  state.activeAgent = outcome.replyBy;
  if (state.agents[outcome.replyBy]) state.agents[outcome.replyBy].mood = outcome.mood || state.agents[outcome.replyBy].mood;
  selectedAgent = outcome.replyBy;
}

async function handleChoice(choice) {
  if (isDialoguePlaying()) return;
  if (state.runEnded || (currentScene().id === "S006" && state.endingResolved)) return;
  const scene = currentScene();
  const playerAgent = choice.playerAgent && state.agents[choice.playerAgent] ? choice.playerAgent : playerAgentForScene(scene);
  const playerSpeaker = playerAgent ? state.agents[playerAgent].name : playerSpeakerForScene(scene);
  document.body.classList.add("is-thinking");
  state.isGenerating = true;
  beginReasoning(choice.player, choice.intent, scene.mode === "classic" ? scene.classicReplyBy : choice.replyBy);
  enqueueLines([makeLine(playerSpeaker, choice.player, { type: "player", agentId: playerAgent || "" })]);

  let outcome;
  if (scene.mode === "classic" && choice.intent !== "ending") {
    outcome = await askClassicModel(choice.player, choice.intent, scene, playerAgent);
  } else if (choice.intent === "ending") {
    outcome = buildEndingOutcome();
  } else {
    outcome = {
      replyBy: choice.replyBy,
      speaker: state.agents[choice.replyBy].name,
      mood: state.agents[choice.replyBy].mood,
      reply: choice.reply,
      voiceText: choice.reply,
      voiceClipId: choice.voiceClipId || "",
      system: choice.system,
      world: choice.world,
      agents: choice.agents,
      memories: choice.memories,
      next: choice.next
    };
  }
  if (scene.mode !== "classic" && choice.intent !== "ending" && providerSelect.value !== "mock") {
    const generated = await askModel(choice.player, choice.intent, {
      replyBy: choice.replyBy,
      transcript: transcriptText()
    });
    outcome.reply = generated.reply;
    outcome.voiceText = generated.voiceText;
    outcome.psychology = generated.psychology;
    outcome.memories = { ...outcome.memories, ...generated.memories };
  }
  await playSerialOutcomes(choice.player, choice.intent, outcome);
  if (choice.intent === "ending") state.endingResolved = true;
  state.history.push({ scene: currentScene().id, input: choice.player, intent: choice.intent });
  state.turn += 1;
  modelState.textContent = providerSelect.value === "mock" ? "本地演示" : "已响应";
  completeReasoning();
  state.isGenerating = false;
  document.body.classList.remove("is-thinking");
  renderAll();
}

async function handlePlayerInput(text) {
  if (isDialoguePlaying()) return;
  if (state.runEnded || (currentScene().id === "S006" && state.endingResolved)) return;
  const trimmed = text.trim();
  if (!trimmed) return;
  const scene = currentScene();
  const playerAgent = playerAgentForScene(scene);
  const playerSpeaker = playerSpeakerForScene(scene);
  const stagedInput = scene.mode === "classic" ? stylizeRoleDuelPlayerLine(playerAgent, trimmed) : trimmed;
  document.body.classList.add("is-thinking");
  state.isGenerating = true;
  const intent = currentScene().id === "S006" ? "ending" : classifyInput(trimmed);
  beginReasoning(trimmed, intent);
  enqueueLines([makeLine(playerSpeaker, stagedInput, { type: "player", agentId: playerAgent || "" })]);

  const outcome = scene.mode === "classic"
    ? await askClassicModel(stagedInput, intent, scene, playerAgent)
    : await askModel(trimmed, intent);
  await playSerialOutcomes(trimmed, intent, outcome);
  if (intent === "ending") state.endingResolved = true;
  state.history.push({ scene: currentScene().id, input: stagedInput, intent });
  state.turn += 1;
  customText.value = "";
  modelState.textContent = providerSelect.value === "mock" ? "本地演示" : "已响应";
  completeReasoning();
  state.isGenerating = false;
  document.body.classList.remove("is-thinking");
  renderAll();
}

async function playSerialOutcomes(playerText, intent, primaryOutcome) {
  const scene = currentScene();
  const generatedLines = [];
  const spoken = new Set();

  applyOutcome(primaryOutcome);
  setReasoningFocus(primaryOutcome.replyBy, `${primaryOutcome.speaker} 已综合玩家输入和上文，决定先抛出立场并改变关系变量。`);
  setReasoningResult(primaryOutcome.replyBy, primaryOutcome.psychology);

  const bridgeLines = (primaryOutcome.bridgeLines || []).map((line) => makeLine(line.speaker, line.text, {
    type: line.type || "system",
    agentId: line.agentId || "",
    voiceText: line.voiceText || "",
    voiceClipId: line.voiceClipId || ""
  }));
  if (bridgeLines.length) {
    enqueueLines(bridgeLines);
    generatedLines.push(...bridgeLines);
  }

  const primaryLine = makeLine(primaryOutcome.speaker, primaryOutcome.reply, {
    agentId: primaryOutcome.replyBy,
    voiceText: primaryOutcome.voiceText || "",
    voiceClipId: primaryOutcome.voiceClipId || ""
  });
  enqueueLines([primaryLine]);
  generatedLines.push(primaryLine);
  spoken.add(primaryOutcome.replyBy);

  if (!primaryOutcome.terminal && scene.id !== "S006" && scene.mode !== "classic") {
    const reactionOrder = scene.participants.filter((id) => !spoken.has(id));
    for (const agentId of reactionOrder) {
      const serialTranscript = transcriptText(generatedLines);
      setReasoningFocus(agentId, `${state.agents[agentId].name} 正在读取前一位发言，将其作为上下文生成串行回应。`);
      const reaction = await askModel(playerText, intent, {
        replyBy: agentId,
        transcript: serialTranscript
      });
      applyOutcome(reaction);
      setReasoningResult(reaction.replyBy, reaction.psychology);
      const line = makeLine(reaction.speaker, reaction.reply, {
        agentId: reaction.replyBy,
        voiceText: reaction.voiceText || "",
        voiceClipId: reaction.voiceClipId || ""
      });
      enqueueLines([line]);
      generatedLines.push(line);
    }
  }

  if (scene.mode !== "classic") {
    maybeEnqueueClassicBeat(generatedLines.length, primaryOutcome);
  }

  if (primaryOutcome.system) {
    enqueueLines([makeLine("系统", primaryOutcome.system, { type: "system" })]);
  }
  if (primaryOutcome.terminal) {
    state.pendingNext = null;
    state.endingResolved = true;
    state.runEnded = true;
  } else {
    state.pendingNext = primaryOutcome.next || null;
  }
}


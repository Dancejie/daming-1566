function voiceAgentForLine(line) {
  return voiceAgentAliases[line?.agentId] || line?.agentId || "";
}

function voiceTextFromStagedLine(text) {
  const normalized = String(text || "").replace(/\s+/g, " ").trim();
  const sentenceStart = normalized.lastIndexOf("。");
  if (sentenceStart >= 0 && sentenceStart < normalized.length - 1) return normalized.slice(sentenceStart + 1).trim();
  const colonStart = Math.max(normalized.lastIndexOf("："), normalized.lastIndexOf(":"));
  if (colonStart >= 0 && colonStart < normalized.length - 1) return normalized.slice(colonStart + 1).trim();
  return normalized;
}


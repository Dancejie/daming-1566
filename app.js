function playTitleBgm() {
  if (!titleBgm) return;
  if (!bgmState.enabled) {
    updateBgmUi("BGM 已关闭");
    return;
  }
  titleBgm.volume = 0.63;
  titleBgm.play()
    .then(() => {
      updateBgmUi("BGM 循环播放中");
    })
    .catch(() => {
      updateBgmUi("点击封面或进入按钮启用 BGM");
    });
}

function pauseTitleBgm(reset = false) {
  if (!titleBgm) return;
  titleBgm.pause();
  if (reset) titleBgm.currentTime = 0;
  updateBgmUi(bgmState.enabled ? "BGM 已暂停" : "BGM 已关闭");
}

function updateBgmUi(note = "") {
  const label = bgmState.enabled ? "BGM 开" : "BGM 关";
  if (bgmToggleBtn) bgmToggleBtn.textContent = label;
  if (titleBgmToggle) titleBgmToggle.textContent = label;
  if (titleAudioNote) titleAudioNote.textContent = note || (bgmState.enabled ? "点击封面空白处播放封面音乐" : "BGM 已关闭");
}

function toggleBgm() {
  bgmState.enabled = !bgmState.enabled;
  if (bgmState.enabled) {
    playTitleBgm();
  } else {
    pauseTitleBgm(false);
  }
}

